import { gradeOf } from './priority.js';

const inr = (n) => `Rs.${Math.round(Number(n) || 0).toLocaleString('en-IN')}`;

/** Deterministic municipal dispatch template — always available offline. */
export function offlineWorkOrder(hotspot, ward) {
  const grade = gradeOf(hotspot.priority_score);
  const chronic = !!hotspot.is_chronic;
  const action = chronic || hotspot.priority_score > 22
    ? 'FULL SUB-BASE RECONSTRUCTION (halt cold-mix patching)'
    : 'COLD-MIX PATCH + CRACK SEALING';
  const tons = asphaltTons(hotspot.priority_score);
  const rebuild = reconstructionCost(hotspot.road_type);
  const saving = annualisedSaving({ detectionCount: hotspot.detection_count, roadType: hotspot.road_type });

  return [
    'COIMBATORE MUNICIPAL CORPORATION — ROAD REPAIR DISPATCH',
    `Ward Office: ${ward}   |   Issued: ${new Date().toLocaleDateString('en-IN')}`,
    `Location: ${hotspot.street_name} (${Number(hotspot.center_lat).toFixed(5)}, ${Number(hotspot.center_lon).toFixed(5)})`,
    `Zone: ${hotspot.zone_name}   |   Road class: ${hotspot.road_type}`,
    '',
    `PRIORITY: ${grade} (score ${hotspot.priority_score})   Chronic: ${chronic ? 'YES' : 'NO'}   Monsoon risk: ${hotspot.monsoon_inundation_risk ? 'YES' : 'NO'}`,
    `EVIDENCE: ${hotspot.detection_count} fleet detections, dominant defect "${hotspot.dominant_class}"`,
    '',
    '1. RECOMMENDED ACTION',
    `   ${action}`,
    '',
    '2. MATERIALS & PLANT',
    `   ${tons} t cold-mix asphalt · ${(tons * 0.08).toFixed(2)} KL bitumen emulsion · 40 m crack sealant`,
    '   Crew: 6 workers + 1 tandem roller + 1 mini-miller + 2 traffic marshals',
    '',
    '3. FINANCIALS',
    `   Band-aid patching today: ${inr(annualPatchSpend(hotspot.detection_count))}/yr`,
    `   Permanent reconstruction: ${inr(rebuild)} (amortised over 3 years)`,
    `   Net annual saving from permanent fix: ${inr(saving)}`,
    '',
    '4. RISK IF DEFERRED',
    '   Water ingress through open cracks strips the binder under bus/lorry load;',
    '   structural collapse is expected within 48 h of the next 25 mm+ rain event,',
    '   creating accident liability and repeat patching cost.',
    '',
    '— Generated by RoadPulse offline municipal template.',
  ].join('\n');
}

async function callLlm(prompt) {
  if (!OPENROUTER_KEY) return null;
  try {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), 12_000);
    const res = await fetch('https://openrouter.ai/api/v1/chat/completions', {
      method: 'POST',
      headers: { Authorization: `Bearer ${OPENROUTER_KEY}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: LLM_MODEL,
        messages: [{ role: 'user', content: prompt }],
        max_tokens: 700,
      }),
      signal: ctrl.signal,
    });
    clearTimeout(timer);
    if (!res.ok) return null;
    const json = await res.json();
    return json.choices?.[0]?.message?.content?.trim() || null;
  } catch {
    return null;
  }
}

/**
 * PRD 4.7 — AI work order generator.
 * Uses the offline template as the baseline and upgrades it with the LLM when a
 * key is configured; the demo never fails.
 */
export async function generateWorkOrder({ hotspot, ward = 'CMC Ward 32 Office', user = null }) {
  const baseline = offlineWorkOrder(hotspot, ward);
  let text = baseline;
  let model = 'offline-template';

  if (OPENROUTER_KEY) {
    const prompt = [
      'You are the Chief Municipal Engineer for Coimbatore Municipal Corporation.',
      'Rewrite the following road repair dispatch as a crisp, formal municipal work order.',
      'Keep every number, location and recommendation exactly. Use plain text, no markdown symbols.',
      '',
      baseline,
    ].join('\n');
    const llm = await callLlm(prompt);
    if (llm) {
      text = llm;
      model = LLM_MODEL;
    }
  }

  const tons = asphaltTons(hotspot.priority_score);
  const info = run(
    `INSERT INTO work_orders
       (hotspot_id, priority_level, asphalt_required_tons, estimated_budget_inr,
        summary_text, assigned_ward_office, status, model, created_by)
     VALUES (?,?,?,?,?,?, 'Issued', ?, ?)`,
    [
      hotspot.hotspot_id,
      gradeOf(hotspot.priority_score),
      tons,
      hotspot.estimated_reconstruct_cost_inr || reconstructionCost(hotspot.road_type),
      text,
      ward,
      model,
      user?.id ?? null,
    ]
  );

  const workOrderId = Number(info.lastInsertRowid);
  run("UPDATE chronic_hotspots SET status = 'Dispatched', assigned_ward_office = ? WHERE hotspot_id = ?", [
    ward,
    hotspot.hotspot_id,
  ]);

  audit({
    userId: user?.id ?? null,
    userEmail: user?.email ?? 'system',
    action: 'workorder.create',
    entity: 'work_order',
    entityId: workOrderId,
    detail: `WO #${workOrderId} for hotspot #${hotspot.hotspot_id} (${gradeOf(hotspot.priority_score)}) → ${ward}`,
  });

  return {
    work_order_id: workOrderId,
    hotspot_id: hotspot.hotspot_id,
    summary_text: text,
    model,
    priority_level: gradeOf(hotspot.priority_score),
    asphalt_required_tons: tons,
    assigned_ward_office: ward,
  };
}

export function listWorkOrders(limit = 50) {
  return query(
    `SELECT w.*, h.street_name, h.zone_name, h.center_lat, h.center_lon
       FROM work_orders w LEFT JOIN chronic_hotspots h ON h.hotspot_id = w.hotspot_id
      ORDER BY w.work_order_id DESC LIMIT ?`,
    [limit]
  );
}

export function getWorkOrder(id) {
  return one(
    `SELECT w.*, h.street_name, h.zone_name, h.center_lat, h.center_lon
       FROM work_orders w LEFT JOIN chronic_hotspots h ON h.hotspot_id = w.hotspot_id
      WHERE w.work_order_id = ?`,
    [id]
  );
}
